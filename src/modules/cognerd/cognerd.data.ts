export function filterPrompts(status?: PromptRecord['status']): PromptRecord[] {
    if (!status) return PROMPTS;
    return PROMPTS.filter((p) => p.status === status);
}

export function filterVisibility(filters: {
    engine?: Engine | 'all';
    mentioned?: 'all' | 'mentioned' | 'cited' | 'not_mentioned';
}): VisibilityRow[] {
    return VISIBILITY_ROWS.filter((row) => {
        if (filters.engine && filters.engine !== 'all' && row.engine !== filters.engine) {
            return false;
        }
        if (filters.mentioned === 'mentioned') return row.mentioned;
        if (filters.mentioned === 'cited') return row.cited;
        if (filters.mentioned === 'not_mentioned') return !row.mentioned;
        return true;
    });
}

export function filterCitations(engine?: Engine | 'all'): CitationRecord[] {
    if (!engine || engine === 'all') return CITATIONS;
    return CITATIONS.filter((c) => c.engine === engine);
}

export function filterBriefs(status?: BriefStatus): ContentBrief[] {
    if (!status) return CONTENT_BRIEFS;
    return CONTENT_BRIEFS.filter((b) => b.status === status);
}
